// Get all unique pincodes for dropdown
export const getUniquePincodes = () => {
  const unique = new Map();
  KASARAGOD_PINCODES.forEach(p => {
    if (!unique.has(p.pincode)) {
      unique.set(p.pincode, p);
    }
  });
  return Array.from(unique.values()).sort((a, b) => a.pincode.localeCompare(b.pincode));
};

// Document validation patterns
export const DOCUMENT_VALIDATORS = {
  aadhar: {
    pattern: /^\d{12}$/,
    format: 'XXXX XXXX XXXX',
    hint: '12 digit number (format: XXXX XXXX XXXX)',
    validate: (num) => /^\d{12}$/.test(num.replace(/\s/g, ''))
  },
  pan: {
    pattern: /^[A-Z]{5}[0-9]{4}[A-Z]{1}$/,
    format: 'AAAAA9999A',
    hint: '10 characters (format: 5 letters, 4 digits, 1 letter)',
    validate: (num) => /^[A-Z0-9]{10}$/.test(num.replace(/\s/g, '').toUpperCase())
  },
  driverlicense: {
    pattern: /^[A-Z]{2}[0-9]{2}[A-Z]{2}[0-9]{7}$/i,
    format: 'AA99AA0000000',
    hint: 'State code + Issue year + 2 letters + 7 digits',
    validate: (num) => /^[A-Z0-9]{13}$/i.test(num.replace(/\s/g, ''))
  },
  passport: {
    pattern: /^[A-Z]{1}[0-9]{7}$/i,
    format: 'A0000000',
    hint: '1 letter + 7 digits',
    validate: (num) => /^[A-Z0-9]{8}$/i.test(num.replace(/\s/g, ''))
  }
};

// Helper function to validate pincode - check if it exists in Kasaragod
export const isValidKasaragodPincode = (pincode) => {
  return KASARAGOD_PINCODES.some(p => p.pincode === pincode);
};

// Get location details from pincode
export const getPincodeDetails = (pincode) => {
  const found = KASARAGOD_PINCODES.find(p => p.pincode === pincode);
  return found || null;
};

// Get all areas for a pincode
export const getAreasForPincode = (pincode) => {
  return KASARAGOD_PINCODES.filter(p => p.pincode === pincode).map(p => p.area);
};

// Get area with pincode formatted string
export const getAreaDisplayName = (area, pincode) => {
  return `${area} - ${pincode}`;
};

// Get all unique pincodes with their first area
export const getAllUniquePincodes = () => {
  return getUniquePincodes().map(p => ({ pincode: p.pincode, firstArea: p.area }));
};

// Validate document number based on type
export const validateDocumentNumber = (type, number) => {
  const validator = DOCUMENT_VALIDATORS[type];
  if (!validator) return false;
  return validator.validate(number);
};

// Get document hint
export const getDocumentHint = (type) => {
  const validator = DOCUMENT_VALIDATORS[type];
  return validator ? validator.hint : '';
};
